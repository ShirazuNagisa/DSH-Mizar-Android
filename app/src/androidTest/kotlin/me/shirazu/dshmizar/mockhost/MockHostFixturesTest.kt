/**
 * The mock host's fixtures, decoded with the production client code.
 *
 * `test/mock-host/mock-host.mjs` exists so the new surfaces (process fold, streamed
 * text, image lightbox, Live Updates) can be screenshotted against a host that
 * pushes exactly the frames a test wants. The risk of a hand-written host is drift:
 * a record shape the projection silently ignores, a state code that moved, an
 * envelope byte out of place. None of those would fail anything until somebody ran
 * the app against it and stared at the screen.
 *
 * So the fixtures are committed here, under `androidTest/assets/mock-host/`, and
 * this test reads them the way the app would:
 *
 *  - the identity/pairing JSON must decode into the kit's own DTOs;
 *  - the record fixture must project into one finished turn with its prompt, its
 *    answer, the folded tool call and its delivered file;
 *  - the pending/stats/maintenance fixtures must decode;
 *  - every emitted state frame must decode through `StateFrameEnvelope` and land in
 *    a `StateChannel` with the state, interval, flags and text the timeline declared.
 *
 * The frame bytes are generated by the host itself and committed alongside the
 * fixtures; `mock-host.mjs --emit-frames` regenerates them. This is the seam where
 * a JS encoder and a Kotlin decoder agree or fail loudly.
 */
@RunWith(AndroidJUnit4::class)
class MockHostFixturesTest {

    private val assets = InstrumentationRegistry.getInstrumentation().context.assets

    private fun assetText(path: String): String = assets.open(path).use { it.readBytes().toString(Charsets.UTF_8) }

    private fun fixtures(): JsonObject = WIRE_JSON.parseToJsonElement(assetText("mock-host/fixtures.json")) as JsonObject

    private fun frames(): JsonObject = WIRE_JSON.parseToJsonElement(assetText("mock-host/frames.json")) as JsonObject

    /**
     * Resolve the `@now` placeholders the fixtures use for relative timestamps.
     *
     * The host does this when it serves the fixture (see `resolveTimestamps`), and
     * the test has to apply the same rule, because `updatedAt` and `time` are
     * numbers on the wire but a committed file cannot say "five seconds ago".
     */
    private fun resolved(element: JsonElement, now: Long = 1_700_000_000_000L): JsonElement = when (element) {
        is JsonPrimitive -> when {
            element.isString && element.content.startsWith("@now") ->
                JsonPrimitive(now + element.content.removePrefix("@now").toLongOrNull().orZero())

            else -> element
        }

        is JsonArray -> JsonArray(element.map { resolved(it, now) })
        is JsonObject -> JsonObject(element.mapValues { resolved(it.value, now) })
    }

    private fun Long?.orZero(): Long = this ?: 0L

    @Test
    fun theIdentityAndPairingFixturesDecodeIntoTheClientDtos() {
        val root = fixtures()
        val host = root.getValue("host").jsonObject
        val hello = WIRE_JSON.decodeFromJsonElement(
            HelloResponse.serializer(),
            buildJsonObject {
                put("hostId", host.getValue("hostId"))
                put("hostName", host.getValue("hostName"))
                put("protocolVersion", host["protocolVersion"] ?: JsonPrimitive(1))
                put("pairingOpen", true)
                put("paired", false)
                put("engines", host["engines"] ?: JsonArray(emptyList()))
            },
        )
        assertEquals("mock-host-1", hello.hostId)
        assertEquals("Mock Studio", hello.hostName)
        assertEquals(2, hello.engines?.size)

        val pairing = root.getValue("pairing").jsonObject
        val pair = WIRE_JSON.decodeFromJsonElement(
            PairResponse.serializer(),
            buildJsonObject {
                put("deviceToken", pairing.getValue("deviceToken"))
                put("deviceId", pairing.getValue("deviceId"))
                put("hostId", host.getValue("hostId"))
                put("hostName", host.getValue("hostName"))
                put("protocolVersion", JsonPrimitive(1))
            },
        )
        assertTrue("a pairing code's token must look usable to the app", pair.deviceToken.startsWith("mzd_"))
        assertEquals("mock-device-1", pair.deviceId)
    }

    @Test
    fun theSessionListFixtureDecodesAndGroups() {
        val root = fixtures()
        val list = WIRE_JSON.decodeFromJsonElement(
            SessionListResult.serializer(),
            buildJsonObject { put("items", resolved(root.getValue("sessions"))) },
        )
        assertEquals(3, list.items.size)
        assertTrue("the fixture must have one running session for the live surfaces", list.items.any { it.running })
        assertEquals("/Users/operator/work/api", list.items.first().cwd)
    }

    @Test
    fun theConversationFixtureProjectsIntoTheTurnTheAppDraws() {
        val root = fixtures()
        val messages = WIRE_JSON.decodeFromJsonElement(
            SessionMessagesResult.serializer(),
            resolved(root.getValue("messages")),
        )
        assertEquals("mock-session-1", messages.sessionId)
        assertNotNull("the page must carry its context so the composer can show it", messages.context)

        val items = Conversation.items(messages)
        assertTrue(
            "the prompt must project; the fixture's kind=user is what allows it",
            items.any { it is ConversationItem.Message && it.role == ConversationItem.Role.USER },
        )
        assertTrue(
            "the answer must project",
            items.any { it is ConversationItem.Message && it.role == ConversationItem.Role.ASSISTANT },
        )
        assertTrue(
            "the tool call must project",
            items.any { it is ConversationItem.Tool && it.name == "shell" },
        )

        val turns = Conversation.turns(messages)
        assertEquals(1, turns.size)
        val turn = turns.single()
        assertEquals(1, turn.turn)
        assertEquals(1, turn.prompts.size)
        // The result is folded into its call, so one tool row and two answers remain.
        assertEquals(1, turn.steps.count { it is ConversationItem.Tool })
        assertEquals("completed", turn.endedReason)
        assertNotNull("the turn must have both ends, or it draws as still running", turn.durationMillis)
        assertEquals(
            "the delivered file is the lightbox's entry point",
            1,
            turn.deliverables.size,
        )
        assertEquals("docs/report.png", turn.deliverables.single().path)
    }

    @Test
    fun thePendingStatsAndMaintenanceFixturesDecode() {
        val root = fixtures()
        val pending = WIRE_JSON.decodeFromJsonElement(
            PendingInteractions.serializer(),
            root.getValue("pending"),
        )
        assertEquals(1, pending.approvals.size)
        assertEquals(1, pending.questions.size)
        assertEquals("shell", pending.approvals.single().toolName)
        assertEquals(1, pending.questions.single().questions.size)

        val stats = WIRE_JSON.decodeFromJsonElement(
            SessionStatsFrame.serializer(),
            root.getValue("stats"),
        )
        assertEquals("Fix the pairing crash", stats.title)
        assertEquals(200_000L, stats.context?.window)
        assertEquals(27, stats.context?.percent)

        val catalog = WIRE_JSON.decodeFromJsonElement(ModelCatalog.serializer(), root.getValue("models"))
        assertEquals("deepseek-v4.1-pro", catalog.defaultSelection?.model)

        val permissions = WIRE_JSON.decodeFromJsonElement(PermissionCatalog.serializer(), root.getValue("permissions"))
        assertEquals("auto", permissions.defaultPreset)

        val usage = WIRE_JSON.decodeFromJsonElement(UsageOverview.serializer(), root.getValue("usage"))
        assertEquals(5, usage.days.size)
        assertTrue("every usage day carries 24 hourly buckets", usage.days.all { it.hours.size == 24 })

        // `session.stream` is the journal a reconnecting client replays: the fixture
        // must decode, and its last entry has to say the answer was final -- a replay
        // that ends mid-stream draws a finished turn as still running.
        val stream = WIRE_JSON.decodeFromJsonElement(
            SessionStreamResult.serializer(),
            root.getValue("stream"),
        )
        assertEquals("mock-session-1", stream.sessionId)
        assertEquals(2, stream.entries.size)
        assertTrue("the replay must end with the final answer flag", stream.entries.last().isFinal)

        // The served files are what file.stat/file.read answer from; a change to the
        // fixture that dropped them would leave the lightbox with nothing to open.
        val files = root.getValue("files").jsonArray
        assertTrue("the image the lightbox opens must be in the fixture", files.any { it.jsonObject["mediaType"]?.jsonPrimitive?.content == "image/png" })
        assertTrue("the text file the preview opens must be in the fixture", files.any { it.jsonObject["mediaType"]?.jsonPrimitive?.content == "text/plain" })
    }

    @Test
    fun everyEmittedStateFrameDecodesIntoTheDeclaredStep() {
        val root = fixtures()
        val timeline = root.getValue("timeline").jsonArray.map { it.jsonObject }
        val steps = timeline.filter { it["type"]?.jsonPrimitive?.content == "state" }
        val emitted = frames().getValue("frames").jsonArray.map { it.jsonObject }
        assertEquals("regenerate frames.json with `node test/mock-host/mock-host.mjs --emit-frames`", steps.size, emitted.size)

        val channel = StateChannel()
        val intervalText = mutableMapOf<Pair<String, Long>, Int>()
        var now = 1_700_000_000_000L
        var finalFrames = 0
        var streamedAnswer: String? = null

        steps.forEachIndexed { index, step ->
            val emittedFrame = emitted[index]
            val bytes = Base64.getDecoder().decode(emittedFrame.getValue("bytes").jsonPrimitive.content)
            val delivered = StateFrameEnvelope.decode(bytes).getOrElse {
                throw AssertionError("frame ${emittedFrame["name"]} does not decode: ${it.message}")
            }
            now += 100
            val applied = channel.apply(delivered.frame, now)
            val frame = delivered.frame

            val expectedState = SessionState.entries.first { it.name == step.getValue("state").jsonPrimitive.content }
            val expectedInterval = step.getValue("interval").jsonPrimitive.content.toLong()
            val declaredFlags = step["flags"]?.jsonArray?.map { it.jsonPrimitive.content }.orEmpty()
            assertEquals("frame ${emittedFrame["name"]} state", expectedState, frame.state)
            assertEquals("frame ${emittedFrame["name"]} interval", expectedInterval, frame.interval)
            assertEquals("frame ${emittedFrame["name"]} session", step.getValue("sessionId").jsonPrimitive.content, delivered.sessionId)
            assertEquals("frame ${emittedFrame["name"]} flags", expectedFlags(declaredFlags), frame.flags.bits)

            val carriesText = "append" in declaredFlags || "snapshot" in declaredFlags
            if (carriesText) {
                val declaredText = step["text"]?.jsonPrimitive?.content.orEmpty()
                assertEquals("frame ${emittedFrame["name"]} text", declaredText, frame.text)
                val key = delivered.sessionId to expectedInterval
                if ("snapshot" in declaredFlags) {
                    // A snapshot starts the interval's text; its seq is where the text begins.
                    assertEquals("a snapshot starts at textSeq 0", 0L, frame.textSeq)
                    intervalText[key] = declaredText.toByteArray(Charsets.UTF_8).size
                } else {
                    assertEquals(
                        "an append must land where the interval's text ends",
                        intervalText[key]?.toLong() ?: 0L,
                        frame.textSeq,
                    )
                    intervalText[key] = (intervalText[key] ?: 0) + declaredText.toByteArray(Charsets.UTF_8).size
                }
            }
            if (StateFrameFlag.FINAL in frame.flags) {
                finalFrames += 1
                // The terminal state that follows starts a new interval and clears the
                // buffer, so the answer is captured where the FINAL frame left it.
                streamedAnswer = channel.text
            }
            if (applied == me.shirazu.mizar.kit.StateApplied.STALE) {
                throw AssertionError("frame ${emittedFrame["name"]} was dropped as stale by the receiver")
            }
        }
        assertEquals("the timeline must end the answer exactly once", 1, finalFrames)
        assertEquals(
            "the answer the timeline streamed is what the channel held when it finished",
            "I found it: `PairingUri.parse` normalises only the host.",
            streamedAnswer,
        )
        assertEquals(
            "the timeline's last state is what a phone would show afterwards",
            SessionState.COMPLETED,
            channel.state,
        )
    }

    /** The flag byte [StateFrameFlag] would produce for a declared flag list. */
    private fun expectedFlags(flags: List<String>): Int = flags.fold(0) { bits, flag ->
        bits or when (flag) {
            "heartbeat" -> StateFrameFlag.HEARTBEAT.mask
            "append" -> StateFrameFlag.APPEND.mask
            "snapshot" -> StateFrameFlag.SNAPSHOT.mask
            "final" -> StateFrameFlag.FINAL.mask
            else -> throw AssertionError("unknown state flag in the fixture: $flag")
        }
    }

    @Test
    fun theFrameFixtureCarriesTheEnvelopeTheSocketUses() {
        val first = frames().getValue("frames").jsonArray.first().jsonObject
        val bytes = Base64.getDecoder().decode(first.getValue("bytes").jsonPrimitive.content)
        // One byte of session-id length, the id, then the 13-byte state frame whose
        // first byte is the magic; a wrong envelope is the failure this test exists for.
        assertEquals("mock-session-1".toByteArray(Charsets.UTF_8).size, bytes[0].toInt())
        assertEquals(StateFrame.MAGIC, bytes[1 + bytes[0]].toInt() and 0xFF)
    }
}
